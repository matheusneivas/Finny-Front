export function resolveIcon(icon?: string | null, fallback = '📦'): string {
  if (!icon) return fallback;
  // Already an emoji (non-ASCII or multi-char)
  if (icon.length <= 2 || /\p{Emoji}/u.test(icon)) return icon;
  const key = icon.toLowerCase().replace(/\s+/g, '-');
  return ICON_MAP[key] ?? ICON_MAP[key.replace(/-/g, '')] ?? fallback;
}
